    /**
     * Combines a translatable lore list ({@link Lang#getList}) with extra
     * lore lines that shouldn't go through the language file (e.g. lines
     * generated by Slimefun's own {@link LoreBuilder}).
     */
    private static String[] lore(List<String> translated, String... extra) {
        final List<String> combined = new ArrayList<>(translated);
        combined.addAll(Arrays.asList(extra));
        return combined.toArray(new String[0]);
    }

